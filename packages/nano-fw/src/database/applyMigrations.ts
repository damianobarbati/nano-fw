import type { Knex } from 'knex';

type Migration = (transaction: Knex.Transaction) => Promise<void>;
type Options = { database: Knex; files: string[]; load: (file: string) => Migration | Promise<Migration> };

const migrationLock = "select pg_advisory_xact_lock(hashtext(current_schema()), hashtext('knex_migrations'))";

export async function applyMigrations({ database, files, load }: Options) {
  await database.transaction(async (trx) => {
    await trx.raw(migrationLock);

    await trx.raw(`create table if not exists knex_migrations (
      id integer generated by default as identity primary key, name text, batch integer, migration_time timestamptz(0)
    )`);
  });

  const applied = await database.raw<{ rows: { name: string }[] }>('select name from knex_migrations');
  const names = new Set(applied.rows.map((row) => row.name));
  const handlers = new Map<string, Migration>();

  for (const file of files) {
    if (!names.has(file)) handlers.set(file, await load(file));
  }

  await database.transaction(async (trx) => {
    await trx.raw(migrationLock);

    const history = await trx.raw<{ rows: { name: string; batch: number }[] }>(
      'select name, batch from knex_migrations',
    );

    const completed = new Set<string>();
    let batch = 1;

    for (const row of history.rows) {
      if (!files.includes(row.name)) throw new Error(`Missing applied migration: ${row.name}`);
      completed.add(row.name);
      batch = Math.max(batch, row.batch + 1);
    }

    for (const file of files) {
      if (completed.has(file)) continue;

      const handler = handlers.get(file);
      if (!handler) throw new Error(`Migration history changed for ${file}. Retry the command.`);
      await handler(trx);
      await trx.raw('insert into knex_migrations (name, batch, migration_time) values (?, ?, now())', [file, batch]);
    }
  });
}

type RunMigrationsOptions = { database: Knex; migrations: Record<string, Migration> };

export const runMigrations = async ({ database, migrations }: RunMigrationsOptions) => {
  const files = Object.keys(migrations).sort();

  await applyMigrations({ database, files, load: (file) => migrations[file] });
};
